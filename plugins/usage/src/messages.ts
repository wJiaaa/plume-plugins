/**
 * 把 `{name}` 换成对应的值。分单复数的句子按 `n` 选：`n` 常是 `toLocaleString()` 过的字（「1,234」），去掉分组符再比。
 */
export function fill(phrase: Phrase, values: Record<string, string | number> = {}): string {
	const one = typeof phrase === "string" ? phrase : Number(String(values.n ?? "").replace(/[^\d.-]/g, "")) === 1 ? phrase.one : phrase.other;
	return one.replace(/\{(\w+)\}/g, (match, key: string) => (key in values ? String(values[key]) : match));
}
